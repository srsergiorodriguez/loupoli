import {
  HalfEdgeMesh,
  type MeshCornerSpec,
  type MeshFaceSpec,
  type Vec2,
  type Vec3
} from './HalfEdgeMesh';
import type { SelectionMode } from '../scene/MeshNode';

/** Human-readable plural labels for element deletion. */
export function deletionLabel(
  mode: SelectionMode,
  count: number
): string {
  const noun = mode === 'vertex' ? 'vertex' : mode === 'edge' ? 'edge' : 'face';
  return `Delete ${count} ${noun}${count === 1 ? '' : 's'}`;
}

/**
 * Rebuild a mesh with the selected faces, or every face incident to the
 * selected edges/vertices, removed.
 *
 * Remaining face corners keep their positions, per-corner UVs, and material
 * slots. Boundary half-edge loops are regenerated by the DCEL builder. Seam
 * flags are not yet remapped across a destructive rebuild; that arrives with the
 * UV/seam editing phase.
 */
export function deleteSelectedElements(
  mesh: HalfEdgeMesh,
  mode: SelectionMode,
  indices: readonly number[]
): HalfEdgeMesh {
  const selected = new Set(
    indices.filter((index) => Number.isInteger(index) && index >= 0)
  );
  if (selected.size === 0) {
    throw new Error('No elements are selected.');
  }

  const faces = new Set<number>();
  if (mode === 'face') {
    for (const face of selected) {
      if (face >= mesh.faceCount) {
        throw new RangeError(`Face ${face} is outside the mesh.`);
      }
      faces.add(face);
    }
  } else if (mode === 'edge') {
    for (const edge of selected) {
      if (edge >= mesh.edgeCount) {
        throw new RangeError(`Edge ${edge} is outside the mesh.`);
      }
      const halfEdge = mesh.edgeHalfEdge[edge];
      const twin = mesh.heTwin[halfEdge];
      if (mesh.heFace[halfEdge] >= 0) {
        faces.add(mesh.heFace[halfEdge]);
      }
      if (mesh.heFace[twin] >= 0) {
        faces.add(mesh.heFace[twin]);
      }
    }
  } else {
    for (const vertex of selected) {
      if (vertex >= mesh.vertexCount) {
        throw new RangeError(`Vertex ${vertex} is outside the mesh.`);
      }
    }
    for (let face = 0; face < mesh.faceCount; face += 1) {
      const start = mesh.faceHalfEdge[face];
      let current = start;
      do {
        if (selected.has(mesh.heOrigin[current])) {
          faces.add(face);
          break;
        }
        current = mesh.heNext[current];
      } while (current !== start);
    }
  }

  if (faces.size === 0) {
    throw new Error('The selection has no adjacent face to remove.');
  }
  if (faces.size >= mesh.faceCount) {
    throw new Error('Cannot delete every face in the mesh.');
  }

  const remaining: MeshFaceSpec[] = [];
  for (let face = 0; face < mesh.faceCount; face += 1) {
    if (faces.has(face)) {
      continue;
    }
    const corners: MeshCornerSpec[] = [];
    const start = mesh.faceHalfEdge[face];
    let current = start;
    do {
      const vertex = mesh.heOrigin[current];
      const positionOffset = vertex * 3;
      const uvOffset = current * 2;
      const position: Vec3 = [
        mesh.positions[positionOffset],
        mesh.positions[positionOffset + 1],
        mesh.positions[positionOffset + 2]
      ];
      const uv: Vec2 = [mesh.heUv[uvOffset], mesh.heUv[uvOffset + 1]];
      corners.push({ position, uv });
      current = mesh.heNext[current];
    } while (current !== start);
    remaining.push({ corners, material: mesh.faceMaterial[face] });
  }

  return HalfEdgeMesh.fromPolygons(remaining);
}

/** Rebuild every face of a mesh into immutable builder specs. */
export function meshFaceSpecs(mesh: HalfEdgeMesh): MeshFaceSpec[] {
  const faces: MeshFaceSpec[] = [];
  for (let face = 0; face < mesh.faceCount; face += 1) {
    const corners: MeshCornerSpec[] = [];
    const start = mesh.faceHalfEdge[face];
    let current = start;
    do {
      const vertex = mesh.heOrigin[current];
      const positionOffset = vertex * 3;
      const uvOffset = current * 2;
      corners.push({
        position: [
          mesh.positions[positionOffset],
          mesh.positions[positionOffset + 1],
          mesh.positions[positionOffset + 2]
        ],
        uv: [mesh.heUv[uvOffset], mesh.heUv[uvOffset + 1]]
      });
      current = mesh.heNext[current];
    } while (current !== start);
    faces.push({ corners, material: mesh.faceMaterial[face] });
  }
  return faces;
}

/**
 * Weld all selected vertices to their average position.
 *
 * Collapsed faces are dropped; the DCEL builder then rejects non-manifold
 * results instead of leaving a silently broken mesh. Per-corner UVs of
 * surviving corners are preserved, while edge seam flags are not yet remapped.
 */
export function mergeSelectedVertices(
  mesh: HalfEdgeMesh,
  indices: readonly number[]
): HalfEdgeMesh {
  const selected = new Set(
    indices.filter((index) => Number.isInteger(index) && index >= 0)
  );
  if (selected.size < 2) {
    throw new Error('Select at least two vertices to merge.');
  }

  let x = 0;
  let y = 0;
  let z = 0;
  for (const vertex of selected) {
    if (vertex >= mesh.vertexCount) {
      throw new RangeError(`Vertex ${vertex} is outside the mesh.`);
    }
    x += mesh.positions[vertex * 3];
    y += mesh.positions[vertex * 3 + 1];
    z += mesh.positions[vertex * 3 + 2];
  }
  x /= selected.size;
  y /= selected.size;
  z /= selected.size;
  const selectedPositions = new Set(
    [...selected].map((vertex) => {
      const offset = vertex * 3;
      return [
        mesh.positions[offset],
        mesh.positions[offset + 1],
        mesh.positions[offset + 2]
      ].join(',');
    })
  );

  const faces: MeshFaceSpec[] = [];
  for (const face of meshFaceSpecs(mesh)) {
    const mapped = face.corners.map((corner) => {
      const isSelected = selectedPositions.has(corner.position.join(','));
      return {
        position: isSelected ? ([x, y, z] as Vec3) : corner.position,
        uv: corner.uv
      };
    });

    // A triangle may emerge when two adjacent corners weld. Remove consecutive
    // duplicates and a duplicate at the wrap point.
    const corners: MeshCornerSpec[] = [];
    for (const corner of mapped) {
      const previous = corners[corners.length - 1];
      if (!previous || previous.position.join(',') !== corner.position.join(',')) {
        corners.push(corner);
      }
    }
    while (
      corners.length > 1 &&
      corners[0].position.join(',') ===
        corners[corners.length - 1].position.join(',')
    ) {
      corners.pop();
    }

    const keys = corners.map((corner) => corner.position.join(','));
    if (corners.length < 3 || new Set(keys).size !== keys.length) {
      continue;
    }
    faces.push({ corners, material: face.material });
  }

  if (faces.length === 0) {
    throw new Error('Merging those vertices would remove every face.');
  }
  return HalfEdgeMesh.fromPolygons(faces);
}

/** One selected boundary edge in its outward boundary direction. */
interface BoundaryChainEdge {
  readonly halfEdge: number;
  readonly from: number;
  readonly to: number;
}

/**
 * Bridge two boundary chains or loops with a strip of quads.
 *
 * The selected boundary half-edges are followed in boundary direction. Exactly
 * two components with equal segment counts are required. The second component
 * is paired in reverse order so adjacent bridge quads share their new side
 * edges, producing a manifold strip for open chains and closed loops.
 */
export function bridgeSelectedEdges(
  mesh: HalfEdgeMesh,
  indices: readonly number[]
): HalfEdgeMesh {
  const unique = new Set(indices);
  if (unique.size === 0) {
    throw new Error('Select at least two boundary edges to bridge.');
  }

  const edges: BoundaryChainEdge[] = [];
  for (const edge of unique) {
    if (!Number.isInteger(edge) || edge < 0 || edge >= mesh.edgeCount) {
      throw new RangeError(`Edge ${edge} is outside the mesh.`);
    }
    const halfEdge = mesh.edgeHalfEdge[edge];
    const twin = mesh.heTwin[halfEdge];
    let boundary: number;
    if (mesh.heFace[halfEdge] === -1) {
      boundary = halfEdge;
    } else if (mesh.heFace[twin] === -1) {
      boundary = twin;
    } else {
      throw new Error('Bridge requires boundary edges.');
    }
    edges.push({
      halfEdge: boundary,
      from: mesh.heOrigin[boundary],
      to: mesh.halfEdgeDestination(boundary)
    });
  }

  const byStart = new Map<number, number>();
  const incoming = new Set<number>();
  for (let i = 0; i < edges.length; i += 1) {
    if (byStart.has(edges[i].from)) {
      throw new Error('Selected boundary edges share a start vertex.');
    }
    byStart.set(edges[i].from, i);
    incoming.add(edges[i].to);
  }

  const used = new Set<number>();
  const components: { edges: number[]; closed: boolean }[] = [];

  const follow = (start: number): { edges: number[]; closed: boolean } => {
    const chain: number[] = [];
    let current = start;
    const seen = new Set<number>();
    while (current !== undefined && !seen.has(current)) {
      seen.add(current);
      used.add(current);
      chain.push(current);
      const next = byStart.get(edges[current].to);
      if (next === undefined) {
        return { edges: chain, closed: false };
      }
      if (next === start) {
        return { edges: chain, closed: true };
      }
      current = next;
    }
    return { edges: chain, closed: false };
  };

  for (let i = 0; i < edges.length; i += 1) {
    if (!used.has(i) && !incoming.has(edges[i].from)) {
      components.push(follow(i));
    }
  }
  for (let i = 0; i < edges.length; i += 1) {
    if (!used.has(i)) {
      components.push(follow(i));
    }
  }

  if (components.length !== 2) {
    throw new Error('Bridge requires exactly two chains or loops of boundary edges.');
  }
  const [first, second] = components;
  if (
    first.edges.length !== second.edges.length ||
    first.edges.length === 0
  ) {
    throw new Error('Bridge chains must have equal segment counts.');
  }
  if (first.closed !== second.closed) {
    throw new Error('Bridge both an open chain and a loop is not supported.');
  }

  const firstVertices = new Set<number>();
  for (const index of first.edges) {
    firstVertices.add(edges[index].from);
    firstVertices.add(edges[index].to);
  }
  for (const index of second.edges) {
    if (
      firstVertices.has(edges[index].from) ||
      firstVertices.has(edges[index].to)
    ) {
      throw new Error('Bridge chains must not share vertices.');
    }
  }

  const corner = (vertex: number, uv: Vec2): MeshCornerSpec => {
    const offset = vertex * 3;
    return {
      position: [
        mesh.positions[offset],
        mesh.positions[offset + 1],
        mesh.positions[offset + 2]
      ],
      uv
    };
  };

  const count = first.edges.length;
  const faces: MeshFaceSpec[] = [...meshFaceSpecs(mesh)];
  for (let segment = 0; segment < count; segment += 1) {
    const a = edges[first.edges[segment]];
    const b = edges[second.edges[count - 1 - segment]];
    const owner = mesh.heFace[mesh.heTwin[a.halfEdge]];
    const material = owner >= 0 ? mesh.faceMaterial[owner] : 0;
    const u0 = segment / count;
    const u1 = (segment + 1) / count;
    faces.push({
      corners: [
        corner(a.from, [u0, 0]),
        corner(a.to, [u1, 0]),
        corner(b.from, [u1, 1]),
        corner(b.to, [u0, 1])
      ],
      material
    });
  }

  return HalfEdgeMesh.fromPolygons(faces);
}

/**
 * Extrude a selected face region outward along its average normal.
 *
 * Every vertex of the region is duplicated by the extrusion distance. The
 * original selected faces are removed, duplicate vertices form the new top
 * faces, and boundary half-edges generate side quads. UVs and materials are
 * copied; edge seam flags are not yet remapped.
 */
export function extrudeSelectedFaces(
  mesh: HalfEdgeMesh,
  indices: readonly number[],
  distance = 0.25
): HalfEdgeMesh {
  const selected = new Set(
    indices.filter((index) => Number.isInteger(index) && index >= 0)
  );
  if (selected.size === 0) {
    throw new Error('Select at least one face to extrude.');
  }
  if (!Number.isFinite(distance) || distance <= 0) {
    throw new Error('Extrude distance must be positive.');
  }
  for (const face of selected) {
    if (face >= mesh.faceCount) {
      throw new RangeError(`Face ${face} is outside the mesh.`);
    }
  }

  let nx = 0;
  let ny = 0;
  let nz = 0;
  for (const face of selected) {
    const normal = mesh.computeFaceNormal(face);
    nx += normal[0];
    ny += normal[1];
    nz += normal[2];
  }
  const length = Math.hypot(nx, ny, nz);
  if (length <= 1e-9) {
    throw new Error('The selected face normals cancel out.');
  }
  const direction: Vec3 = [nx / length, ny / length, nz / length];
  const offset: Vec3 = [
    direction[0] * distance,
    direction[1] * distance,
    direction[2] * distance
  ];

  const duplicate = new Map<number, Vec3>();
  for (const face of selected) {
    const start = mesh.faceHalfEdge[face];
    let current = start;
    do {
      const vertex = mesh.heOrigin[current];
      if (!duplicate.has(vertex)) {
        duplicate.set(vertex, [
          mesh.positions[vertex * 3] + offset[0],
          mesh.positions[vertex * 3 + 1] + offset[1],
          mesh.positions[vertex * 3 + 2] + offset[2]
        ]);
      }
      current = mesh.heNext[current];
    } while (current !== start);
  }

  const faces: MeshFaceSpec[] = [];
  const base = meshFaceSpecs(mesh);
  for (let face = 0; face < mesh.faceCount; face += 1) {
    if (!selected.has(face)) {
      faces.push(base[face]);
    }
  }

  for (const face of selected) {
    const corners: MeshCornerSpec[] = [];
    const start = mesh.faceHalfEdge[face];
    let current = start;
    do {
      const vertex = mesh.heOrigin[current];
      const uvOffset = current * 2;
      const position = duplicate.get(vertex);
      if (!position) {
        throw new Error('Extrude duplicate vertex is missing.');
      }
      corners.push({
        position: [...position] as Vec3,
        uv: [mesh.heUv[uvOffset], mesh.heUv[uvOffset + 1]]
      });
      current = mesh.heNext[current];
    } while (current !== start);
    faces.push({ corners, material: mesh.faceMaterial[face] });
  }

  for (const face of selected) {
    const start = mesh.faceHalfEdge[face];
    let current = start;
    do {
      const twin = mesh.heTwin[current];
      const twinFace = mesh.heFace[twin];
      if (twinFace !== -1 && selected.has(twinFace)) {
        current = mesh.heNext[current];
        continue;
      }
      const a = mesh.heOrigin[current];
      const next = mesh.heNext[current];
      const b = mesh.heOrigin[next];
      const topA = duplicate.get(a);
      const topB = duplicate.get(b);
      if (!topA || !topB) {
        throw new Error('Extrude boundary duplicate is missing.');
      }
      const uvAOffset = current * 2;
      const uvBOffset = next * 2;
      faces.push({
        material: mesh.faceMaterial[face],
        corners: [
          {
            position: [
              mesh.positions[a * 3],
              mesh.positions[a * 3 + 1],
              mesh.positions[a * 3 + 2]
            ],
            uv: [mesh.heUv[uvAOffset], mesh.heUv[uvAOffset + 1]]
          },
          {
            position: [
              mesh.positions[b * 3],
              mesh.positions[b * 3 + 1],
              mesh.positions[b * 3 + 2]
            ],
            uv: [mesh.heUv[uvBOffset], mesh.heUv[uvBOffset + 1]]
          },
          {
            position: [...topB] as Vec3,
            uv: [mesh.heUv[uvBOffset], mesh.heUv[uvBOffset + 1]]
          },
          {
            position: [...topA] as Vec3,
            uv: [mesh.heUv[uvAOffset], mesh.heUv[uvAOffset + 1]]
          }
        ]
      });
      current = mesh.heNext[current];
    } while (current !== start);
  }

  return HalfEdgeMesh.fromPolygons(faces);
}

/**
 * Inset one face by moving its corners toward its centroid.
 *
 * The original face is replaced by an inner face and a ring of side quads.
 * Per-corner UVs and materials are preserved; only one face may be inset
 * because independent adjacent insets would duplicate boundary edges.
 */
export function insetSelectedFace(
  mesh: HalfEdgeMesh,
  face: number,
  amount = 0.2
): HalfEdgeMesh {
  if (!Number.isInteger(face) || face < 0 || face >= mesh.faceCount) {
    throw new RangeError(`Face ${face} is outside the mesh.`);
  }
  if (!Number.isFinite(amount) || amount <= 0 || amount >= 1) {
    throw new Error('Inset amount must be between 0 and 1.');
  }

  const start = mesh.faceHalfEdge[face];
  const original: MeshCornerSpec[] = [];
  let current = start;
  let cx = 0;
  let cy = 0;
  let cz = 0;
  let count = 0;
  do {
    const vertex = mesh.heOrigin[current];
    const offset = vertex * 3;
    const uvOffset = current * 2;
    const position: Vec3 = [
      mesh.positions[offset],
      mesh.positions[offset + 1],
      mesh.positions[offset + 2]
    ];
    original.push({
      position,
      uv: [mesh.heUv[uvOffset], mesh.heUv[uvOffset + 1]]
    });
    cx += position[0];
    cy += position[1];
    cz += position[2];
    count += 1;
    current = mesh.heNext[current];
  } while (current !== start);
  cx /= count;
  cy /= count;
  cz /= count;

  const inner = original.map((corner): MeshCornerSpec => ({
    position: [
      corner.position[0] + (cx - corner.position[0]) * amount,
      corner.position[1] + (cy - corner.position[1]) * amount,
      corner.position[2] + (cz - corner.position[2]) * amount
    ],
    uv: [...corner.uv] as Vec2
  }));

  const faces: MeshFaceSpec[] = [];
  const base = meshFaceSpecs(mesh);
  for (let candidate = 0; candidate < mesh.faceCount; candidate += 1) {
    if (candidate !== face) {
      faces.push(base[candidate]);
    }
  }
  faces.push({ corners: inner, material: mesh.faceMaterial[face] });

  for (let index = 0; index < original.length; index += 1) {
    const nextIndex = (index + 1) % original.length;
    const a = original[index];
    const b = original[nextIndex];
    const ai = inner[index];
    const bi = inner[nextIndex];
    faces.push({
      material: mesh.faceMaterial[face],
      corners: [
        { position: [...a.position] as Vec3, uv: [...a.uv] as Vec2 },
        { position: [...b.position] as Vec3, uv: [...b.uv] as Vec2 },
        { position: [...bi.position] as Vec3, uv: [...b.uv] as Vec2 },
        { position: [...ai.position] as Vec3, uv: [...a.uv] as Vec2 }
      ]
    });
  }

  return HalfEdgeMesh.fromPolygons(faces);
}

/** A face corner with its outgoing edge for loop-cut processing. */
interface LoopCorner {
  readonly vertex: number;
  readonly edge: number;
  readonly position: Vec3;
  readonly uv: Vec2;
}

function faceLoopCorners(mesh: HalfEdgeMesh, face: number): LoopCorner[] {
  const corners: LoopCorner[] = [];
  const start = mesh.faceHalfEdge[face];
  let current = start;
  do {
    const vertex = mesh.heOrigin[current];
    const offset = vertex * 3;
    const uvOffset = current * 2;
    corners.push({
      vertex,
      edge: mesh.heEdge[current],
      position: [
        mesh.positions[offset],
        mesh.positions[offset + 1],
        mesh.positions[offset + 2]
      ],
      uv: [mesh.heUv[uvOffset], mesh.heUv[uvOffset + 1]]
    });
    current = mesh.heNext[current];
  } while (current !== start);
  return corners;
}

function otherFace(
  mesh: HalfEdgeMesh,
  edge: number,
  face: number
): number | null {
  const halfEdge = mesh.edgeHalfEdge[edge];
  const first = mesh.heFace[halfEdge];
  const second = mesh.heFace[mesh.heTwin[halfEdge]];
  if (first === face) {
    return second >= 0 ? second : null;
  }
  if (second === face) {
    return first >= 0 ? first : null;
  }
  return null;
}

/**
 * Cut one quad edge loop at a position along its crossing edges.
 *
 * The selected edge seeds a walk across opposite quad edges in both
 * directions. Every quad in that ring is split into two quads along the new
 * edge. Position 0.5 cuts at the midpoints; other values slide the loop toward
 * the lower-index endpoint of each crossed edge. Non-quad faces in the ring are
 * rejected. UVs are interpolated per face and materials are preserved; seam
 * flags are not remapped.
 */
export function loopCutFromEdge(
  mesh: HalfEdgeMesh,
  edge: number,
  position = 0.5
): HalfEdgeMesh {
  if (!Number.isInteger(edge) || edge < 0 || edge >= mesh.edgeCount) {
    throw new RangeError(`Edge ${edge} is outside the mesh.`);
  }
  if (!Number.isFinite(position) || position <= 0 || position >= 1) {
    throw new Error('Loop cut position must be between 0 and 1.');
  }
  const halfEdge = mesh.edgeHalfEdge[edge];
  const firstFace = mesh.heFace[halfEdge];
  const secondFace = mesh.heFace[mesh.heTwin[halfEdge]];
  if (firstFace === -1 && secondFace === -1) {
    throw new Error('Loop cut requires a face adjacent to the edge.');
  }

  const loopEdges = new Set<number>([edge]);
  const visitedFaces = new Set<number>();
  const maxFaces = mesh.faceCount * 2 + 4;

  const isQuad = (face: number): boolean => {
    const corners = faceLoopCorners(mesh, face);
    return corners.length === 4;
  };

  const walk = (startFace: number): void => {
    let currentFace = startFace;
    let currentEdge = edge;
    while (currentFace >= 0 && !visitedFaces.has(currentFace)) {
      if (visitedFaces.size > maxFaces) {
        throw new Error('Loop cut could not close its edge ring.');
      }
      if (!isQuad(currentFace)) {
        throw new Error('Loop cut requires a loop of quads.');
      }
      visitedFaces.add(currentFace);
      const corners = faceLoopCorners(mesh, currentFace);
      const index = corners.findIndex((corner) => corner.edge === currentEdge);
      if (index < 0) {
        throw new Error('Loop cut lost the current edge.');
      }
      const opposite = corners[(index + 2) % 4].edge;
      if (loopEdges.has(opposite)) {
        return;
      }
      loopEdges.add(opposite);
      const next = otherFace(mesh, opposite, currentFace);
      if (next === null) {
        return;
      }
      currentEdge = opposite;
      currentFace = next;
    }
  };

  if (firstFace >= 0) {
    walk(firstFace);
  }
  if (secondFace >= 0) {
    walk(secondFace);
  }

  if (loopEdges.size < 2) {
    throw new Error('Loop cut needs a closed opposite edge.');
  }

  // Give every crossed edge a stable A→B direction. Adjacent faces must agree
  // on those labels, otherwise a slide at t != 0.5 moves different sides of
  // the loop in opposite directions and visibly twists it.
  const [edgeStart, edgeEnd] = mesh.getEdgeVertices(edge);
  const edgeLabels = new Map<number, { a: number; b: number }>();
  edgeLabels.set(edge, { a: edgeStart, b: edgeEnd });
  const cornerCache = new Map<number, LoopCorner[]>();
  const cornersOf = (face: number): LoopCorner[] => {
    let corners = cornerCache.get(face);
    if (!corners) {
      corners = faceLoopCorners(mesh, face);
      cornerCache.set(face, corners);
    }
    return corners;
  };
  let labelChanged = true;
  let labelPasses = 0;
  while (labelChanged && labelPasses < mesh.faceCount * 2) {
    labelChanged = false;
    labelPasses += 1;
    for (let face = 0; face < mesh.faceCount; face += 1) {
      const corners = cornersOf(face);
      const selectedIndices: number[] = [];
      for (let index = 0; index < corners.length; index += 1) {
        if (loopEdges.has(corners[index].edge)) {
          selectedIndices.push(index);
        }
      }
      if (selectedIndices.length !== 2) {
        continue;
      }
      const firstIndex = selectedIndices[0];
      const secondIndex = selectedIndices[1];
      if ((secondIndex - firstIndex + 4) % 4 !== 2) {
        continue;
      }
      const firstEdge = corners[firstIndex].edge;
      const secondEdge = corners[secondIndex].edge;
      const knownFirst = edgeLabels.get(firstEdge);
      const knownSecond = edgeLabels.get(secondEdge);

      const derive = (
        known: { a: number; b: number },
        knownIndex: number,
        otherEdge: number
      ): void => {
        const origin = corners[knownIndex];
        const next = corners[(knownIndex + 1) % 4];
        const oppositeOrigin = corners[(knownIndex + 2) % 4];
        const oppositeNext = corners[(knownIndex + 3) % 4];
        let oppositeA: number;
        if (known.a === origin.vertex) {
          // The A/B rail enters at the edge origin; it exits through the
          // opposite edge's last corner.
          oppositeA = oppositeNext.vertex;
        } else if (known.a === next.vertex) {
          oppositeA = oppositeOrigin.vertex;
        } else {
          throw new Error('Loop cut edge labels do not match their face.');
        }
        const oppositeB =
          oppositeA === oppositeOrigin.vertex
            ? oppositeNext.vertex
            : oppositeOrigin.vertex;
        edgeLabels.set(otherEdge, { a: oppositeA, b: oppositeB });
        labelChanged = true;
      };

      if (knownFirst && !knownSecond) {
        derive(knownFirst, firstIndex, secondEdge);
      } else if (knownSecond && !knownFirst) {
        derive(knownSecond, secondIndex, firstEdge);
      }
    }
  }

  const faces: MeshFaceSpec[] = [];
  for (let face = 0; face < mesh.faceCount; face += 1) {
    const corners = cornersOf(face);
    const selectedIndices: number[] = [];
    for (let index = 0; index < corners.length; index += 1) {
      if (loopEdges.has(corners[index].edge)) {
        selectedIndices.push(index);
      }
    }
    if (selectedIndices.length === 0) {
      faces.push(...meshFaceSpecs(mesh).slice(face, face + 1));
      continue;
    }
    if (corners.length !== 4 || selectedIndices.length !== 2) {
      throw new Error('Loop cut encountered a non-quad edge ring.');
    }
    const opposite =
      (selectedIndices[0] + 2) % 4 === selectedIndices[1];
    if (!opposite) {
      throw new Error('Loop cut ring does not cross opposite edges.');
    }

    const pivot = selectedIndices[0];
    const ordered = [0, 1, 2, 3].map(
      (offset) => corners[(pivot + offset) % 4]
    );
    // Move from each edge's label-A endpoint toward label B. The labels were
    // propagated through the ring, so both rails advance together even on a
    // cube whose vertex numbering is not globally consistent.
    const cutPoint = (edgeIndex: number): MeshCornerSpec => {
      const corner = corners[edgeIndex];
      const next = corners[(edgeIndex + 1) % 4];
      const label = edgeLabels.get(corner.edge);
      if (!label) {
        throw new Error('Loop cut could not orient every crossed edge.');
      }
      let start: LoopCorner;
      let end: LoopCorner;
      if (label.a === corner.vertex && label.b === next.vertex) {
        start = corner;
        end = next;
      } else if (label.a === next.vertex && label.b === corner.vertex) {
        start = next;
        end = corner;
      } else {
        throw new Error('Loop cut edge labels do not match their face.');
      }
      return {
        position: [
          start.position[0] +
            (end.position[0] - start.position[0]) * position,
          start.position[1] +
            (end.position[1] - start.position[1]) * position,
          start.position[2] +
            (end.position[2] - start.position[2]) * position
        ],
        uv: [
          start.uv[0] + (end.uv[0] - start.uv[0]) * position,
          start.uv[1] + (end.uv[1] - start.uv[1]) * position
        ]
      };
    };
    const midA = cutPoint(pivot);
    const midB = cutPoint((pivot + 2) % 4);
    const material = mesh.faceMaterial[face];

    faces.push({
      corners: [
        { position: [...ordered[0].position] as Vec3, uv: [...ordered[0].uv] as Vec2 },
        { position: [...midA.position] as Vec3, uv: [...midA.uv] as Vec2 },
        { position: [...midB.position] as Vec3, uv: [...midB.uv] as Vec2 },
        { position: [...ordered[3].position] as Vec3, uv: [...ordered[3].uv] as Vec2 }
      ],
      material
    });
    faces.push({
      corners: [
        { position: [...midA.position] as Vec3, uv: [...midA.uv] as Vec2 },
        { position: [...ordered[1].position] as Vec3, uv: [...ordered[1].uv] as Vec2 },
        { position: [...ordered[2].position] as Vec3, uv: [...ordered[2].uv] as Vec2 },
        { position: [...midB.position] as Vec3, uv: [...midB.uv] as Vec2 }
      ],
      material
    });
  }

  return HalfEdgeMesh.fromPolygons(faces);
}
